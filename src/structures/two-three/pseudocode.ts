      '    x = z.middle',
      '    if x.right ≠ NIL then',
      '        Set_Children(y, y.left, x.left, NIL)',
      '        Set_Children(x, x.middle, x.right, NIL)',
      '    else Set_Children(x, y.left, x.left, x.middle)',
