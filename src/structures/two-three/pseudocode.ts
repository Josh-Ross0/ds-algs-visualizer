      '        delete y',
      '        Set_Children(z, x, z.right, NIL)',
      '    return z',
      '▷ y == z.right',
      'x = z.middle',
      'if x.right ≠ NIL then',
      '    Set_Children(y, x.right, y.left, NIL)',
      '    Set_Children(x, x.left, x.middle, NIL)',
